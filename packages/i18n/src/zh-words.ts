/**
 * 中文**詞庫**：不是介面文字，是拿來比對「人打進來的中文」用的字詞。
 *
 * 為什麼住在 i18n：`tools/i18n-guard` 掃 `apps/web/src` 之內任何中文字（連
 * 正則都當成字串咬），只有 `packages/i18n` 是允許有中文的地方。把「用哪些字
 * 去認人打的中文」放在介面文字旁邊，總好過在守門測試開一個例外 —— 例外一
 * 開，就再也分不出「這是詞庫」還是「這是我懶得抽字串」。
 *
 * 這裡的每一條都只做「認得出來」，不做判斷；判斷在 `apps/web/src/design/
 * brandCustom.ts`。
 */

/**
 * 「自己發明一套顏色／字體／標誌」這類講法。
 *
 * 通用槽（#34）明寫「不准發明新色、新字、新標誌」，所以自定義頁的 brief 這
 * 樣寫就是撞。中間容許十幾個字，是因為人會寫「自己重新設計一套品牌用的顏
 * 色」而不是「發明色」。
 */
export const INVENT_ASSET_PATTERN =
  /(發明|自創|自己定|自己發明|另外定|重新設計|新做)[^。；，,]{0,12}(色|顏色|色彩|字體|字型|字|標誌|logo|icon)/i;

/** 自定義頁不做的範圍：渠道尺寸與頁數（#41 的「不做什麼」）。 */
export const CHANNEL_SCOPE_PATTERN = /渠道尺寸|渠道規格|渠道大小|頁數/;

/**
 * 通用槽裡最該被引用的那一句。
 *
 * 先找明寫「不准發明」的那句（那正是 brief 撞的東西）；沒有就找任何一句
 * 「不准」；連那句都沒有就回空字串 —— 空字串在畫面上會顯示成「通用槽沒有
 * 這一句」，比拿一句無關的話充數誠實。
 */
export function pickPolicyLine(lines: string[]): string {
  return (
    lines.find((line) => line.includes('不准發明')) ??
    lines.find((line) => line.includes('不准')) ??
    ''
  );
}
